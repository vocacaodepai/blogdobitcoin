import type { StockPhoto } from "./pexels";

const COMMONS_API = "https://commons.wikimedia.org/w/api.php";

// A política de uso da API do Wikimedia (https://meta.wikimedia.org/wiki/User-Agent_policy)
// exige um User-Agent identificando a aplicação com um jeito de contato;
// sem isso o tráfego é tratado como anônimo e sofre limite de taxa mais
// agressivo (já vimos erro 429 em produção sem esse header).
const COMMONS_HEADERS = {
  "User-Agent": "BlogDoBitcoin/1.0 (https://www.blogdobitcoin.com.br; contato@blogdobitcoin.com.br)",
};

function stripHtml(html: string): string {
  return html.replace(/<[^>]*>/g, "").trim();
}

type CommonsImageInfo = {
  url: string;
  thumburl?: string;
  width: number;
  height: number;
  extmetadata?: {
    LicenseShortName?: { value: string };
    Artist?: { value: string };
    ObjectName?: { value: string };
    ImageDescription?: { value: string };
    Categories?: { value: string };
  };
};

/** Capa fixada no conteúdo: `imageQuery: "File:Nome exato do arquivo.jpg"` (arquivo do Commons conferido à mão). */
export function isPinnedFile(query: string): boolean {
  return /^File:/i.test(query.trim());
}

function normalize(text: string): string {
  return text
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/\.[a-z0-9]{3,4}$/, "")
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
}

// Palavras que descrevem o tipo de foto, não o assunto: não contam como "nome" na conferência.
const GENERIC = new Set(
  "a an and the of in on at with de do da dos das e em no na com para por um uma portrait logo photo photograph picture image building headquarters office statue closeup close up screen device".split(
    " "
  )
);
// Palavras que podem aparecer no nome de um arquivo de logo sem mudar de quem é o logo.
const LOGO_NOISE = new Set(
  "logo logos logotype wordmark icon symbol emblem mark color colour colored full black white text horizontal vertical small large big transparent official png svg jpg new old square round dark light background bg file".split(
    " "
  )
);

/**
 * Confere se o arquivo achado fala mesmo do assunto da busca, porque a busca do Commons é
 * solta: "Solana logo" já devolveu foto do político Javier Solana, "Mark Karpeles portrait"
 * devolveu uma pintura de 1921, "Banco Central do Brasil building" devolveu o banco central
 * da Argentina. Regras:
 * - nomes próprios (palavras com inicial maiúscula na busca) aparecem todos no título, na
 *   descrição ou nas categorias do arquivo; em "portrait", todos no próprio título;
 * - em "logo", o título tem que ser de logo e não pode trazer outro nome (o logo do
 *   Ethereum Classic não serve para "Ethereum logo");
 * - em busca descritiva, pelo menos metade das palavras do assunto aparece no arquivo.
 */
function isRelevant(title: string, info: CommonsImageInfo, query: string): boolean {
  const q = query.trim();
  const kind = /\blogo$/i.test(q) ? "logo" : /\bportrait$/i.test(q) ? "portrait" : "topic";
  const words = q.split(/\s+/).filter(Boolean);
  // Siglas de 1 ou 2 letras ("US", "EU") quase nunca aparecem iguais no nome do arquivo: não contam.
  const keep = (w: string) => w.length >= 3 && !GENERIC.has(w);
  const proper = words.filter((w) => /^\p{Lu}/u.test(w)).flatMap((w) => normalize(w).split(" ")).filter(keep);
  const subject = words.flatMap((w) => normalize(w).split(" ")).filter(keep);
  const meta = info.extmetadata;
  const fileTitle = normalize(title.replace(/^File:/i, ""));
  const hay = normalize(
    [title, meta?.ObjectName?.value ?? "", stripHtml(meta?.ImageDescription?.value ?? ""), (meta?.Categories?.value ?? "").replace(/\|/g, " ")].join(" ")
  );
  // Imagem gerada por IA também aparece no Commons: nunca serve de capa.
  if (/\b(dall e|midjourney|stable diffusion|ai generated|generated by ai|gerada por ia)\b/.test(hay)) return false;
  const hayWords = new Set(hay.split(" "));
  const titleWords = new Set(fileTitle.split(" "));
  // Palavra descritiva pode vir colada no arquivo ("hardwarewallet"); nome próprio só vale inteiro.
  const loose = (set: Set<string>, joined: string, w: string) => set.has(w) || (w.length >= 6 && joined.replace(/ /g, "").includes(w));

  if (kind === "portrait") {
    // O nome inteiro, na ordem, no título: "James Howells" não casa com "James Whistler, Mildred Howells".
    const name = proper.join(" ");
    return proper.length > 0 && ` ${fileTitle} `.includes(` ${name} `);
  }
  if (kind === "logo") {
    if (!/\b(logo|logos|logotype|wordmark|icon|symbol|emblem)\b/.test(fileTitle)) return false;
    if (!subject.every((w) => titleWords.has(w))) return false;
    const extra = fileTitle.split(" ").filter((w) => w && !/^\d+$/.test(w) && !LOGO_NOISE.has(w) && !subject.includes(w));
    return extra.length === 0;
  }
  if (proper.length > 0 && !proper.every((w) => hayWords.has(w))) return false;
  const hits = subject.filter((w) => loose(hayWords, hay, w)).length;
  return subject.length === 0 || hits >= Math.ceil(subject.length / 2);
}

function toStockPhoto(title: string, info: CommonsImageInfo, query: string): StockPhoto | null {
  // Sem metadado de licença explícito, não arrisca publicar a foto.
  const license = info.extmetadata?.LicenseShortName?.value;
  if (!license) return null;

  const artist = info.extmetadata?.Artist?.value ? stripHtml(info.extmetadata.Artist.value) : "Wikimedia Commons";
  const pageUrl = `https://commons.wikimedia.org/wiki/${encodeURIComponent(title)}`;

  return {
    url: info.thumburl || info.url,
    width: info.width,
    height: info.height,
    alt: query,
    photographer: `${artist} (${license})`,
    photographerUrl: pageUrl,
    source: "Wikimedia Commons",
  };
}

/**
 * Busca uma foto real licenciada (Creative Commons/domínio público) no
 * Wikimedia Commons: prioridade para pessoas, empresas e produtos reais
 * citados no texto, antes de cair em banco de imagem genérico (Pexels/
 * Pixabay). Só devolve foto com metadado de licença explícito, para nunca
 * publicar imagem sem atribuição correta.
 */
export async function getWikimediaImage(query: string, seed = 0): Promise<StockPhoto | null> {
  try {
    const params = new URLSearchParams({
      action: "query",
      format: "json",
      generator: "search",
      gsrsearch: `${query} filetype:bitmap`,
      gsrnamespace: "6",
      gsrlimit: "8",
      prop: "imageinfo",
      iiprop: "url|size|extmetadata",
      iiurlwidth: "1600",
      origin: "*",
    });
    const res = await fetch(`${COMMONS_API}?${params.toString()}`, {
      headers: COMMONS_HEADERS,
      next: { revalidate: 60 * 60 * 24 * 7 },
    });
    if (!res.ok) return null;

    const data = await res.json();
    const pages = data?.query?.pages as
      | Record<string, { title: string; index?: number; imageinfo?: CommonsImageInfo[] }>
      | undefined;
    if (!pages) return null;

    const licensed = Object.values(pages)
      .filter((p) => p.imageinfo && p.imageinfo[0] && isRelevant(p.title, p.imageinfo[0], query))
      .sort((a, b) => (a.index ?? 0) - (b.index ?? 0))
      .map((p) => toStockPhoto(p.title, p.imageinfo![0], query))
      .filter((p): p is StockPhoto => p !== null);

    if (licensed.length === 0) return null;
    return licensed[seed % licensed.length];
  } catch {
    return null;
  }
}

/**
 * Busca a ficha de licença/crédito de um arquivo específico do Wikimedia
 * Commons, dado o título exato (ex.: "File:Elon Musk 2015.jpg"). Usada pela
 * Google Custom Search (lib/google-cse.ts) depois de localizar a página do
 * arquivo, para confirmar a licença antes de usar a imagem.
 */
export async function getWikimediaFileInfo(title: string, query: string, checkRelevance = false): Promise<StockPhoto | null> {
  try {
    const params = new URLSearchParams({
      action: "query",
      format: "json",
      titles: title,
      prop: "imageinfo",
      iiprop: "url|size|extmetadata",
      iiurlwidth: "1600",
      origin: "*",
    });
    const res = await fetch(`${COMMONS_API}?${params.toString()}`, {
      headers: COMMONS_HEADERS,
      next: { revalidate: 60 * 60 * 24 * 7 },
    });
    if (!res.ok) return null;

    const data = await res.json();
    const pages = data?.query?.pages as
      | Record<string, { title: string; imageinfo?: CommonsImageInfo[] }>
      | undefined;
    if (!pages) return null;

    const page = Object.values(pages)[0];
    if (!page?.imageinfo?.[0]) return null;
    if (checkRelevance && !isRelevant(page.title, page.imageinfo[0], query)) return null;

    return toStockPhoto(page.title, page.imageinfo[0], query);
  } catch {
    return null;
  }
}
